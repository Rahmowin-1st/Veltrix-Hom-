/** Opaque composite pagination cursor over (created_at, id). base64url so it
 *  survives a URL query param unescaped. */
function encodeCursor(createdAt: string, id: string): string {
  return Buffer.from(JSON.stringify({ t: createdAt, i: id }), 'utf8').toString('base64url')
}
function decodeCursor(raw: string): { t: string; i: string } | null {
  try {
    const parsed = JSON.parse(Buffer.from(raw, 'base64url').toString('utf8')) as { t?: unknown; i?: unknown }
    if (typeof parsed.t === 'string' && typeof parsed.i === 'string') return { t: parsed.t, i: parsed.i }
    return null
  } catch { return null }
}

