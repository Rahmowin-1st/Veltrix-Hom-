chatRouter.get('/:chatId', requireAuth, async (req, res, next) => {
  try {
    const userId = req.userId!
    // Long chats must not ship hundreds of messages on open. We fetch the
    // NEWEST window (descending + limit) and reverse it for display; older
    // messages arrive on demand via ?before=<ISO timestamp>.
    const limit = Math.min(Math.max(Number(req.query.limit ?? 40) || 40, 10), 100)
    const rawCursor = typeof req.query.before === 'string' ? req.query.before : null
    const cursor = rawCursor ? decodeCursor(rawCursor) : null

    let messageQuery = admin
      .from('messages')
      .select('id,role,content,blocks,attachments,detected_subject,source_mode,created_at')
      .eq('chat_id', req.params.chatId)
      .eq('user_id', userId)
      .order('created_at', { ascending: false })
      .order('id', { ascending: false })
      .limit(limit + 1) // one extra row tells us whether more remain
    if (cursor) {
      // Composite keyset cursor: strictly older than (created_at, id). When
      // several messages share a created_at (a user + assistant pair inserted
      // in the same millisecond), the id tie-break stops a page boundary from
      // skipping or repeating a message.  (V9 2.9)
      messageQuery = messageQuery.or(`created_at.lt.${cursor.t},and(created_at.eq.${cursor.t},id.lt.${cursor.i})`)
    } else if (rawCursor) {
      // Backward compatibility: an older client may still send a bare ISO
      // timestamp. Fall back to the timestamp-only comparison for it.
      messageQuery = messageQuery.lt('created_at', rawCursor)
    }

    const [{ data: chat, error: chatError }, { data: newestFirst, error: messageError }, { data: links, error: linkError }] = await Promise.all([
      admin.from('chats').select('id,title,updated_at,pinned,project_id,draft,skill_id,locked_source_id').eq('id', req.params.chatId).eq('user_id', userId).maybeSingle(),
      messageQuery,
      admin.from('chat_sources').select('source_id').eq('chat_id', req.params.chatId).eq('user_id', userId).order('created_at', { ascending: true }),
    ])
    if (chatError) throw chatError
    if (!chat) return res.status(404).json({ message: 'Chat topilmadi yoki bu akkauntga tegishli emas.' })
    if (messageError) throw messageError
    if (linkError) throw linkError

    const rows = newestFirst ?? []
    const hasMore = rows.length > limit
    const page = hasMore ? rows.slice(0, limit) : rows
    const messages = [...page].reverse() // back to chronological for the UI
    const oldest = messages[0]
    const oldestCursor = oldest ? encodeCursor(String(oldest.created_at), String(oldest.id)) : null

    const sourceIds = (links ?? []).map((row) => row.source_id)
    if (!sourceIds.length && chat.locked_source_id) sourceIds.push(chat.locked_source_id)
    res.json({ chat, sourceIds, messages, hasMore, oldestCursor })
  } catch (e) { next(e) }
})
