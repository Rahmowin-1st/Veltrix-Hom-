chatRouter.get('/requests/:clientRequestId', requireAuth, async (req, res, next) => {
  try {
    const userId = req.userId!
    const clientRequestId = req.params.clientRequestId ?? ''
    if (!/^[0-9a-f-]{36}$/i.test(clientRequestId)) {
      return res.status(400).json({ code: 'bad_request_id', message: 'Noto\'g\'ri so\'rov identifikatori.' })
    }

    const { data: request, error } = await admin
      .from('chat_requests')
      .select('id,status,chat_id,response_snapshot,error_code,error_message,assistant_message_id')
      .eq('user_id', userId)
      .eq('client_request_id', clientRequestId)
      .maybeSingle()
    if (error) throw error
    if (!request) return res.status(404).json({ code: 'not_found', message: 'So\'rov topilmadi.' })

    if (request.status === 'completed') {
      const snapshot = (request.response_snapshot ?? {}) as Record<string, unknown>
      return res.json({
        code: 'completed', chatId: request.chat_id,
        messageId: request.assistant_message_id, ...snapshot,
      })
    }
    if (request.status === 'claimed' || request.status === 'processing') {
      return res.json({ code: 'processing', chatId: request.chat_id })
    }
    if (request.status === 'uncertain') {
      return res.json({
        code: 'uncertain', chatId: request.chat_id,
        message: 'Oldingi urinish holati noaniq. Qayta yuborishni tasdiqlang.',
      })
    }
    return res.json({
      code: 'failed', chatId: request.chat_id,
      errorCode: request.error_code, message: request.error_message ?? 'So\'rov bajarilmadi.',
    })
  } catch (e) { next(e) }
})

